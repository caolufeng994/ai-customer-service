def _add_table(doc: Document, header: list[str], rows: list[list[str]]) -> None:
    """插入一个带表头的表格（用于验证解析器能否提取表格文本）。"""
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    for cell, text in zip(table.rows[0].cells, header):
        cell.text = text
        for p in cell.paragraphs:
            for run in p.runs:
                run.bold = True
    for row in rows:
        cells = table.add_row().cells
        for cell, text in zip(cells, row):
            cell.text = text


def _build(title: str, blocks: list) -> Document:
    """blocks 元素形如 ("h1"/"h2"/"p"/"li", 内容) 或 ("table", (表头, 行))。"""
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(10.5)

    doc.add_heading(title, level=0)
    for kind, payload in blocks:
        if kind == "h1":
            doc.add_heading(payload, level=1)
        elif kind == "h2":
            doc.add_heading(payload, level=2)
        elif kind == "p":
            doc.add_paragraph(payload)
        elif kind == "li":
            doc.add_paragraph(payload, style="List Bullet")
        elif kind == "table":
            _add_table(doc, payload[0], payload[1])
    return doc


